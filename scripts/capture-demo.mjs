import assert from 'node:assert/strict';
import { execFile } from 'node:child_process';
import { existsSync, mkdirSync, renameSync, writeFileSync } from 'node:fs';
import { resolve } from 'node:path';
import { promisify } from 'node:util';
import { chromium, expect } from '@playwright/test';

const exec = promisify(execFile), output = resolve('test-results/demo-media');
const origin = new URL(process.env.E2E_BASE_URL);
assert.equal(origin.protocol, 'http:');
assert.equal(origin.hostname, '127.0.0.1');
assert.equal(origin.pathname, '/');
assert(!origin.username && !origin.password && !origin.search && !origin.hash);
const project = process.env.E2E_COMPOSE_PROJECT;
assert.match(project ?? '', /^demo-recording-[a-f0-9]{8}$/);
assert(process.env.E2E_COMPOSE_ENV_FILE);
const compose = ['compose', '-p', project, '--env-file', resolve(process.env.E2E_COMPOSE_ENV_FILE), '-f', 'compose.yaml', '-f', 'compose.demo.yaml'];
const web = JSON.parse((await exec('docker', ['inspect', '--format', '{{json .}}', `${project}-web-1`], { timeout: 10000 })).stdout);
assert.equal(web.Config.Labels['com.docker.compose.project'], project);
assert.equal(web.Config.Labels['com.docker.compose.service'], 'web');
assert.deepEqual(web.NetworkSettings.Ports['8080/tcp'], [{ HostIp: origin.hostname, HostPort: origin.port || '80' }], 'Browser origin must belong to the selected demo web service');
assert.equal((await exec('docker', [...compose, 'exec', '-T', 'api', 'node', '-p', 'process.env.APP_ORIGIN'], { timeout: 10000 })).stdout.trim(), origin.origin);
const sql = async query => (await exec('docker', [...compose, 'exec', '-T', 'db', 'psql', '-U', 'demo_local', '-d', 'chat_demo', '-tAc', query], { timeout: 10000 })).stdout.trim();
assert.equal(await sql("SELECT current_database(),current_user,shobj_description(oid,'pg_database') FROM pg_database WHERE datname=current_database()"), 'chat_demo|demo_local|real-time-chat:local-demo:v1');
assert.equal(await sql('SELECT (SELECT count(*) FROM "User"),(SELECT count(*) FROM "Session"),(SELECT count(*) FROM "Channel"),(SELECT count(*) FROM "Membership"),(SELECT count(*) FROM "Message")'), '2|0|2|4|111', 'Capture requires a freshly seeded disposable demo');
for (const name of ['ALICE', 'BOB']) assert(process.env[`DEMO_${name}_PASSWORD`]?.length >= 15, 'Supply local demo credentials');
assert(!existsSync(`${output}/demo.webm`), 'Move the previous capture directory before recording again');
mkdirSync(output, { recursive: true });

const browser = await chromium.launch(), contexts = [], phases = [];
const options = { baseURL: origin.origin, viewport: { width: 1280, height: 900 }, locale: 'en-US', timezoneId: 'UTC' };
const context = async extra => { const ctx = await browser.newContext({ ...options, ...extra }); contexts.push(ctx); return ctx; };
const login = async (ctx, name) => {
  const page = await ctx.newPage();
  await page.goto('/login');
  await page.getByLabel('Email address', { exact: true }).fill(`${name}@demo.example.test`);
  await page.getByLabel('Password', { exact: true }).fill(process.env[`DEMO_${name.toUpperCase()}_PASSWORD`]);
  await page.getByRole('button', { name: 'Sign in', exact: true }).click();
  await expect(page.getByText('Live connection established.', { exact: true })).toBeVisible();
  return page;
};
const rows = page => page.getByRole('log').locator('[data-message-id]');
const send = async (page, body) => {
  await page.getByLabel('Message', { exact: true }).pressSequentially(body, { delay: 35 });
  await page.getByRole('button', { name: 'Send message', exact: true }).click();
  await expect(rows(page).filter({ hasText: body })).toHaveCount(1);
};
let recording, aliceSocket, started;
try {
  const auth = await context(), bobContext = await context();
  await login(auth, 'alice');
  const bob = await login(bobContext, 'bob');
  await bob.getByRole('button', { name: 'Open chat Demo Planning', exact: true }).click();
  await expect(rows(bob)).toHaveCount(6);
  const aliceContext = await context({ storageState: await auth.storageState(), recordVideo: { dir: output, size: options.viewport } });
  await auth.close();
  const alice = await aliceContext.newPage(); recording = alice.video(); started = performance.now();
  const phase = text => phases.push({ seconds: (performance.now() - started) / 1000, text });
  // Deliberate reading pauses affect only presentation, after real state assertions.
  const pause = () => alice.waitForTimeout(6000);
  await alice.routeWebSocket('**/socket.io/**', socket => { aliceSocket = socket; socket.connectToServer(); });
  phase('Alice is already signed in. Open the shared Demo Planning channel.');
  await alice.goto('/workspace');
  await expect(alice.getByRole('heading', { name: 'Welcome, Alice Rivera', exact: true })).toBeVisible();
  await pause();
  await alice.getByRole('button', { name: 'Open chat Demo Planning', exact: true }).click();
  await expect(rows(alice)).toHaveCount(6);
  await expect.poll(() => !!aliceSocket).toBe(true);
  phase('Send a message. Confirmed means it is saved, not that somebody read it.');
  await send(alice, 'Can we review the release checklist here?'); await pause();
  phase('Bob replies from an independent browser session.');
  await send(bob, 'Yes. I will check the rollout notes.');
  await expect(rows(alice).filter({ hasText: 'Yes. I will check the rollout notes.' })).toHaveCount(1);
  await alice.getByRole('heading', { name: '#demo-planning', exact: true }).scrollIntoViewIfNeeded();
  await alice.screenshot({ path: `${output}/chat-desktop.png`, fullPage: true }); await pause();
  phase('Only Alice goes offline. The real server and Bob stay connected.');
  await aliceContext.setOffline(true); await aliceSocket.close({ code: 1001, reason: 'Demo network interruption' });
  await expect(alice.getByText('Connection interrupted. Reconnecting…', { exact: true })).toBeVisible();
  await alice.getByRole('heading', { name: 'Welcome, Alice Rivera', exact: true }).scrollIntoViewIfNeeded();
  await alice.screenshot({ path: `${output}/chat-offline.png`, fullPage: true }); await pause();
  const draft = 'Back online. Thanks for checking the plan.';
  await alice.getByLabel('Message', { exact: true }).pressSequentially(draft, { delay: 35 });
  await expect(alice.getByRole('button', { name: 'Send message', exact: true })).toBeDisabled();
  phase('Bob sends two messages while Alice is offline. Her draft remains unsent.');
  await send(bob, 'The checklist is ready for review.');
  await send(bob, 'I also checked the migration plan.');
  await expect(rows(alice)).toHaveCount(8); await pause();
  phase('Reconnect Alice. Persisted messages arrive through bounded recovery.');
  const recoveryResponse = alice.waitForResponse(response => new URL(response.url()).pathname.endsWith('/messages/sync') && response.status() === 200, { timeout: 20000 });
  await aliceContext.setOffline(false); await alice.bringToFront();
  // Reconnect includes transport timeout/backoff; use the existing recovery E2E's 20s bound.
  await expect(alice.getByText('Live connection established.', { exact: true })).toBeVisible({ timeout: 20000 });
  const recoveryPage = await (await recoveryResponse).json();
  expect(recoveryPage.items.map(item => item.body)).toEqual(expect.arrayContaining(['The checklist is ready for review.', 'I also checked the migration plan.']));
  await expect(rows(alice)).toHaveCount(10, { timeout: 20000 });
  await expect(alice.getByLabel('Message', { exact: true })).toHaveValue(draft);
  await expect(rows(alice)).toContainText(['The checklist is ready for review.', 'I also checked the migration plan.']);
  assert.equal(new Set(await rows(alice).evaluateAll(nodes => nodes.map(node => node.getAttribute('data-message-id')))).size, 10);
  await alice.getByRole('heading', { name: '#demo-planning', exact: true }).scrollIntoViewIfNeeded();
  await alice.screenshot({ path: `${output}/chat-recovered.png`, fullPage: true }); await pause();
  phase('Send the retained draft. Recovery does not provide durable offline sending.');
  await alice.getByRole('button', { name: 'Send message', exact: true }).click();
  await expect(rows(alice).filter({ hasText: draft })).toHaveCount(1);
  await expect(rows(bob).filter({ hasText: draft })).toHaveCount(1);
  await expect(rows(alice)).toHaveCount(11); await pause();
  const duration = (performance.now() - started) / 1000;
  await aliceContext.close();
  renameSync(await recording.path(), `${output}/demo.webm`);

  const stillContext = await context({ storageState: await bobContext.storageState() }), still = await stillContext.newPage();
  await still.goto('/'); await expect(still.getByRole('heading', { name: 'Try the local demo', exact: true })).toBeVisible();
  await still.screenshot({ path: `${output}/overview-desktop.png`, fullPage: true });
  await still.setViewportSize({ width: 375, height: 812 });
  assert(await still.locator('html').evaluate(element => element.scrollWidth <= element.ownerDocument.defaultView.innerWidth));
  await still.screenshot({ path: `${output}/overview-mobile.png`, fullPage: true });
  await still.goto('/workspace');
  await still.getByRole('button', { name: 'Open chat Demo Planning', exact: true }).click();
  await expect(rows(still)).toHaveCount(11);
  assert(await still.locator('html').evaluate(element => element.scrollWidth <= element.ownerDocument.defaultView.innerWidth));
  await still.screenshot({ path: `${output}/chat-mobile.png`, fullPage: true });
  const timestamp = value => new Date(Math.round(value * 1000)).toISOString().slice(11, 23);
  writeFileSync(`${output}/demo.en.vtt`, 'WEBVTT\n\n' + phases.map((item, index) => `${index + 1}\n${timestamp(item.seconds)} --> ${timestamp(phases[index + 1]?.seconds ?? duration)}\n${item.text}\n`).join('\n'));
  writeFileSync(`${output}/capture.json`, JSON.stringify({ viewport: options.viewport, mobileViewport: { width: 375, height: 812 }, durationSeconds: duration, initialRows: 6, offlineRows: 8, recoveredRows: 10, recoveryPageMessages: recoveryPage.items.length, finalRows: 11, phases }, null, 2) + '\n');
  console.info('Demo captured with confirmed cross-session delivery, retained draft and 10 distinct recovered rows.');
} finally {
  await Promise.allSettled(contexts.map(ctx => ctx.close()));
  await browser.close();
}
